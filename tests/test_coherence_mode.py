def test_manifest_flag_only_when_on():
    assert not any("ETX_DSL_COH_L1" in line for line in guard_block({}))
    assert "#define ETX_DSL_COH_L1 1" in guard_block({"coh_l1": 1})


def test_dsl_accessors_load_at_agent_scope_and_store_at_system_scope_under_l1():
    h = coh.HELPERS
    assert "#if defined(ETX_DSL_COH) || defined(ETX_DSL_COH_L1)" in h and "#define ETX_DSL_COH_L1_IMPL 1" in h
    l1 = h[h.index("#ifdef ETX_DSL_COH_L1"):h.index("#endif", h.index("#ifdef ETX_DSL_COH_L1"))]
    assert "#define DSL_COH_LD_SCOPE __HIP_MEMORY_SCOPE_AGENT" in l1
    loads = re.findall(r"__hip_atomic_load\([^;]*?, (\w+)\)", h)
    stores = re.findall(r"__hip_atomic_store\([^;]*?, (\w+)\)", h)
    assert loads and set(loads) == {"DSL_COH_LD_SCOPE"}
    assert stores and set(stores) == {"DSL_COH_SCOPE"}


def test_deepseek_build_wide_switch_equals_its_own_switch(monkeypatch):
    """ETX_COHERENCE=l1 (system) and ETX_DSV2_COH=l1 (DeepSeek's own) give the same tiles the same coherence."""
    from examples.dsv2lite import graph
    for k in ("ETX_COHERENCE", "ETX_DSV2_COH"):
        monkeypatch.delenv(k, raising=False)
    monkeypatch.setenv("ETX_DSV2_COH", "l1")
    g1 = compile_graph(graph.build(), "gfx942", {}, {}).graph
    monkeypatch.delenv("ETX_DSV2_COH")
    monkeypatch.setenv("ETX_COHERENCE", "l1")
    g2 = compile_graph(graph.build(), "gfx942", {}, {}).graph
    assert [(x.name, x.body.coherence) for x in g1.grids] == [(x.name, x.body.coherence) for x in g2.grids]
    assert {x.name for x in g2.grids if x.body.coherence != "coherent_l1"} == {"dense_dn_0"}


