"""G6 (docs/core/INVENTORY-SYSTEM-2026-10-13.md 4.1): `coherent_l1` as ONE build-wide compiler mode (ETX_COHERENCE=l1 /
PassOptions.coherence), taken by every tile whose FAMILY declares it, for any model. Default byte-identical; the DSL
family's accessors switch to agent-scope loads through the feature manifest; fleet's through its lever; a plan in l1
with tiles that do not implement it is refused."""
from __future__ import annotations

from pathlib import Path
import re

import pytest

from etx.codegen import emit_kernel
from etx.codegen.manifest import guard_block
from etx.frontends import hip_link
from etx.ir import Graph, Resource
from etx.ops import coh
from etx.passes import compile_graph
from etx.passes.plan import PassOptions

RES = Resource(threads=256, lds_bytes=0, vgpr=64)


def _graph(caps_b=("coherent_l1",), caps_a=()):
    """a -> b -> c on one domain; c on another (E2 DEVICE)."""
    g = Graph("mode")
    g.tensor("t", (64,), role="activation", bytes_per_elem=2)
    g.etensor("E1", (1,), wait_count=4)
    g.etensor("E2", (1,), wait_count=4)
    g.call_device("a", (4,), hip_link("a.hip", "etx_tile_a", coherence_caps=caps_a), resource=RES, args=["t"],
                  out_edges={"E1": "i->(0)"}, domain_map="i->(0)", duration_us=1.0)
    g.call_device("b", (4,), hip_link("b.hip", "etx_tile_b", coherence_caps=caps_b), resource=RES, args=["t"],
                  in_edges={"E1": "i->(0)"}, out_edges={"E2": "i->(0)"}, domain_map="i->(0)", duration_us=1.0)
    g.call_device("c", (1,), hip_link("c.hip", "etx_tile_c"), resource=RES, args=["t"],
                  in_edges={"E2": "i->(0)"}, domain_map="i->(1)", duration_us=1.0)
    return g


def test_default_mode_changes_nothing(monkeypatch):
    monkeypatch.delenv("ETX_COHERENCE", raising=False)
    assert PassOptions().coherence == "declared"
    plain = emit_kernel(compile_graph(_graph(caps_b=()), "gfx942", {}, {}))
    capable = emit_kernel(compile_graph(_graph(), "gfx942", {}, {}))
    assert plain == capable                               # declaring a capability alone changes no generated byte
    assert "coherent-L1" not in capable and "ETX_DSL_COH_L1" not in capable


def test_l1_switches_exactly_the_declaring_tiles(monkeypatch):
    monkeypatch.setenv("ETX_COHERENCE", "l1")
    g = _graph()
    plan = compile_graph(g, "gfx942", {}, {})
    assert [gr.body.coherence for gr in plan.graph.grids] == ["imported", "coherent_l1", "imported"]
    assert [gr.body.coherence for gr in g.grids] == ["imported"] * 3          # the caller's graph is not mutated
    src = emit_kernel(plan)
    assert "coherent-L1 tile: no acquire invalidate" in src
    assert "#define ETX_DSL_COH_L1 1" in src                                     # the manifest publishes the mode
    inline = emit_kernel(compile_graph(_graph(), "gfx942", {}, {}, PassOptions(inline_tiles=True)))
    assert "#if defined(ETX_DSL_COH_HELPERS) && !defined(ETX_DSL_COH_L1_IMPL)" in inline   # stale DSL source refused
    assert "write it back" not in src                     # a coherent-L1 consumer adds no write-back
    assert re.search(r"etx_arrive_flush_DEVICE(_s)?\(", src) and "_nf(" not in src   # plain-store family: flush kept
    assert any("coherence=l1: 1 of 3 grids" in line for line in plan.log)


def test_write_through_family_keeps_flush_free_arrives(monkeypatch):
    """The DSL family's stores are system scope: as a coherent-L1 producer it keeps the no-flush arrive."""
    monkeypatch.setenv("ETX_COHERENCE", "l1")
    plan = compile_graph(_graph(caps_b=("coherent_l1", "coherent_stores")), "gfx942", {}, {})
    assert plan.events["E2"].producers_coherent
    assert re.search(r"etx_arrive_flush_DEVICE(_s)?_nf\(", emit_kernel(plan))


