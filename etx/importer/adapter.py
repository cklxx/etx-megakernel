"""ETX tiles for imported kernels: one link-mode tile per import (etx_tile_<export>).

The thread index is passed through a volatile asm: everything a kernel derives from its thread id alone is
invariant in the persistent loop, and without the barrier LLVM hoists those values out of every inlined
tile into the loop preheader, where they stay live together (measured: 38 VGPR spills with the Qwen3-8B
tile set, 0 per tile alone).

A task of an imported grid runs `slots` of the kernel's original blocks side by side: slot s of task t is
block t * slots + s. The kernel's argument block for this grid instance is at byte c->cst[0] of the grid's
first argument (one buffer holds the blocks of every instance; etx.importer.argblock lays them out), and
ends with u32 grid[3], u32 nblocks. Waves beyond the last slot and slots past the last block do nothing.

The slot index is wave-uniform (a slot is whole waves, ir_import.py slot_thr), but it derives from the opaque thread
index, so the compiler treated it as per-lane: with slots > 1 the block index, the slot switch of the imported entry
and the kernel's block-derived index math all went to VGPRs. Mixtral's attention (attn_mfma4_g4 at 4 slots, 128 VGPR
cap) spilled 96 of the megakernel's 100 spilled VGPRs there. __builtin_amdgcn_readfirstlane makes it an SGPR again; it
stays inside the task (it reads the asm result), so nothing is hoisted into the persistent loop's preheader.
Measured (ROCm 7.14, gfx942, entry defaults): Mixtral 100 -> 60 spilled VGPRs (-> 10 with the uniform BIGK branch in
etx/ops/gemv.py), Qwen3-8B 10 -> 6, Qwen3-30B-A3B 9 -> 8 (its SGPR spills 144 -> 262, into VGPR lanes, no scratch).
"""
from __future__ import annotations


def emit_adapters(imports: dict) -> str:
    lds = max([i["lds_bytes"] for i in imports.values()] + [16])
    out = ["// generated by etx.importer.adapter: ETX tiles for kernels imported at the IR level", "#pragma once",
           "#define ETX_HAS_IMPORTS 1", f"#define ETX_IMPORT_LDS {lds}",
           f"#define ETX_IMPORT_SLOTS {max([i['slots'] for i in imports.values()] + [1])}   // one set of slot-barrier words per slot",
           '#include "etx/abi.h"', '#include "etx/import.h"', ""]
    for e, i in imports.items():
        if i.get("dsl"):                                     # an ETX op (etx.ops): its tiles come from its own generator
            continue
        st, k, g = i["slot_threads"], i["slots"], i["grid_offset"]
        # a kernel whose block is smaller than the workgroup has slot barriers: with hardware barrier rounds every wave
        # runs the round protocol around its block (etx/import.h); otherwise idle waves may leave at once
        rounds = bool(i.get("slot_barrier")) and i.get("barriers", 0) > 0
        nbytes = (g + 16 + 63) // 64 * 64                    # the argument block and its grid words
        begin = "  etx_imp_rounds_begin();" if rounds else ""
        end_ = "  etx_imp_rounds_end();" if rounds else ""
        leave = "" if rounds else f"  if (slot >= {k}) return;"
        guard = f"slot < {k} && blk < nblk" if rounds else "blk < nblk"
        out += [f"// {i.get('spec', i['kernel'])}  block {tuple(i['block'])}, {k} slot(s) of {st} threads, {i['lds_bytes']} B LDS"
                + (", barriers in rounds" if rounds else ""),
                f'extern "C" __device__ void etx_imp_{e}(const void* args, int blk, int tid, int slot);',
                f'extern "C" __device__ __attribute__((always_inline)) void etx_tile_{e}(const etx_ctx* c) {{',
                "  int tx; asm volatile(\"v_mov_b32 %0, %1\" : \"=v\"(tx) : \"v\"((int)threadIdx.x));   // opaque per task: see below",
                f"  const int slot = __builtin_amdgcn_readfirstlane(tx / {st}), tid = tx - slot * {st};",
                leave,
                "  const unsigned char* a = etx_imp_argblock(c->args, c->cst[0]);",
                f"  const int nblk = *(const int*)(a + {g + 12});",
                f"  const int blk = c->coord[0] * {k} + slot;",
                begin,
                f"  if ({guard}) etx_imp_{e}(a, blk, tid, slot);",
                end_,
                "}",
                f"// before the task's event wait (wave 0): its argument block into the scalar cache",
                f'extern "C" __device__ __attribute__((always_inline)) void etx_pre_{e}(const etx_ctx* c) {{ etx_imp_touch(etx_imp_argblock(c->args, c->cst[0]), {nbytes}); }}',
                f'static __device__ __attribute__((always_inline)) void etx_pre_{e}_at(const etx_ctx* c, int off) {{ etx_imp_touch(etx_imp_argblock(c->args, off), {nbytes}); }}',
                f'extern "C" __device__ __attribute__((always_inline)) void etx_pre_x_{e}(const etx_ctx* c) {{ '
                f'etx_imp_touch(etx_imp_argblock(c->args, c->cst[0] + c->coord[0] * c->cst[1]), {nbytes}); }}',
                f"// every block of one launch on this workgroup, {k} at a time (chained tasks, see examples/vllm_llm ETX_VL_CHAIN);",
                "// waves past the last slot skip the calls but take every barrier",
                f"static __device__ __attribute__((always_inline)) void etx_all_blocks_{e}(const unsigned char* a) {{",
                "  int tx; asm volatile(\"v_mov_b32 %0, %1\" : \"=v\"(tx) : \"v\"((int)threadIdx.x));",
                f"  const int slot = __builtin_amdgcn_readfirstlane(tx / {st}), tid = tx - slot * {st};",
                f"  const int nblk = *(const int*)(a + {g + 12});",
                f"  for (int first = 0; first < nblk; first += {k}) {{",
                f"    const int blk = first + slot;",
                "  " + begin if rounds else "",
                f"    if (slot < {k} && blk < nblk) etx_imp_{e}(a, blk, tid, slot);",
                "  " + end_ if rounds else "    __syncthreads();",
                "  }",
                "}",
                "// XCD replica r (= the task's coordinate, pinned to XCD r): optionally copy src -> dst first (an in-place",
                "// kernel then works on its XCD's own copy), then every block of launch r; cst = {block 0, stride, copies or -1}",
                f'extern "C" __device__ __attribute__((always_inline)) void etx_tile_rep_{e}(const etx_ctx* c) {{',
                "  const unsigned char* base = etx_imp_argblock(c->args, 0);",
                "  const int r = c->coord[0];",
                "  if (c->cst[2] >= 0) {",
                "    const unsigned long long* d = (const unsigned long long*)(base + c->cst[2] + r * 32);   // src, dst, bytes",
                "    const uint4* src = (const uint4*)d[0]; uint4* dst = (uint4*)d[1]; const int n = (int)(d[2] / 16);",
                "    for (int i = threadIdx.x; i < n; i += blockDim.x) dst[i] = src[i];",
                "    __syncthreads();",
                "  }",
                f"  etx_all_blocks_{e}(base + c->cst[0] + r * c->cst[1]);",
                "}",
                "// grid (XCDs, tasks per XCD) pinned xw->x: the task reads its XCD's argument block; cst = {block 0, stride, tasks per XCD}",
                f'extern "C" __device__ __attribute__((always_inline)) void etx_tile_x_{e}(const etx_ctx* c) {{',
                "  int tx; asm volatile(\"v_mov_b32 %0, %1\" : \"=v\"(tx) : \"v\"((int)threadIdx.x));",
                f"  const int slot = __builtin_amdgcn_readfirstlane(tx / {st}), tid = tx - slot * {st};",
                leave,
                "  const unsigned char* a = etx_imp_argblock(c->args, c->cst[0] + c->coord[0] * c->cst[1]);",
                f"  const int nblk = *(const int*)(a + {g + 12});",
                f"  const int blk = (c->coord[0] * c->cst[2] + c->coord[1]) * {k} + slot;",
                begin,
                f"  if ({guard}) etx_imp_{e}(a, blk, tid, slot);",
                end_,
                "}", ""]
    return "\n".join(x for x in out if x != "")


def ntasks(info: dict, grid: tuple[int, int, int]) -> int:
    n = grid[0] * grid[1] * grid[2]
    return (n + info["slots"] - 1) // info["slots"]


_TY = {"i1": "b", "i8": "b", "i16": "s", "i32": "i", "i64": "l", "float": "f", "double": "d", "half": "h", "bfloat": "h"}


def emit_host_header(imports: dict) -> str:
    """C++ descriptors of every import's argument block, for the host (offsets and a type code per parameter:
    p pointer, i i32, l i64, f float, d double, b bool/i8, s i16, h 16-bit float)."""
    out = ["// generated by etx.importer.adapter: argument-block layouts of the imported kernels", "#pragma once",
           "struct etx_imp_desc { const char* name; int nparams; int arg_bytes; int grid_off; int off[32]; char ty[33]; int block[3]; };", ""]
    for e, i in imports.items():
        ps = i["params"]
        if len(ps) > 32:
            raise ValueError(f"{e}: more than 32 parameters")
        offs = ", ".join(str(p["offset"]) for p in ps) or "0"
        tys = "".join("p" if p["ty"].startswith("ptr") else _TY[p["ty"]] for p in ps)
        b = i["block"]
        out.append(f'static const etx_imp_desc etx_imp_{e}_desc = {{"{e}", {len(ps)}, {i["arg_bytes"]}, {i["grid_offset"]}, {{{offs}}}, "{tys}", {{{b[0]}, {b[1]}, {b[2]}}}}};')
    out.append("")
    out.append("static const etx_imp_desc* etx_imp_find(const char* name) {")
    for e in imports:
        out.append(f'  if (!__builtin_strcmp(name, "{e}")) return &etx_imp_{e}_desc;')
    out.append("  return nullptr;")
    out.append("}")
    from etx.importer.spec import emit_validation, emit_model_validation
    out.append(emit_validation(imports))
    out.append(emit_model_validation(imports))
    return "\n".join(out) + "\n"


def main():
    import argparse
    import json
    from pathlib import Path
    ap = argparse.ArgumentParser(description="adapter tiles + host header from imports.json")
    ap.add_argument("imports"); ap.add_argument("--tiles", required=True); ap.add_argument("--header", required=True)
    a = ap.parse_args()
    imp = json.loads(Path(a.imports).read_text())
    from etx.importer.spec import OPERATORS, validate_import
    for export, info in imp.items():
        if export in OPERATORS:
            validate_import(export, info)
    Path(a.tiles).write_text(emit_adapters(imp))
    Path(a.header).write_text(emit_host_header(imp))
    from etx.importer.spec import emit_host_files
    emit_host_files(Path(a.header).parent)


if __name__ == "__main__":
    main()
