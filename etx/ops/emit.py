"""Emit the tiles of the requested ETX ops into one source file and add their argument layouts to an imports.json
(what examples/vllm_llm/build.sh runs between the import and the adapter):

  python3 -m etx.ops.emit IMPORTS_JSON --tiles OUT.hip --ops gemv,topk
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from etx.ops import attnprep, gemv, topk, prims

OPS = {"gemv": gemv, "topk": topk, "attnprep": attnprep}
HEADER = ['// generated by etx.ops.emit: the ETX DSL ops of this build', "#pragma once",
          '#include "etx/abi.h"', "@ETX_IMPORT_LDS@", '#include "etx/import.h"', '#include "etx/tile_util.h"', ""]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("imports_json")
    ap.add_argument("--tiles", required=True)
    ap.add_argument("--machine", default="gfx942")
    ap.add_argument("--ops", required=True, help="comma-separated: " + ", ".join(OPS))
    a = ap.parse_args()
    imp = json.loads(Path(a.imports_json).read_text())
    threads = max([i.get("threads", 1024) for i in imp.values()] + [1024])
    src = list(HEADER)
    for name in filter(None, a.ops.split(",")):
        op = OPS[name]
        imp.update(op.import_entries(threads, machine=a.machine) if name == "gemv" else op.import_entries(threads))
        body = op.emit_tiles()
        # each op's source is self-contained; the common includes are here once
        src.append("\n".join(ln for ln in body.splitlines() if not ln.startswith(("#pragma once", "#include", "// generated by"))))
    Path(a.imports_json).write_text(json.dumps(imp, indent=1))
    # Size the import arena BEFORE include "etx/import.h" (which declares etx_lds_arena[ETX_IMPORT_LDS]). The arena
    # must hold the largest tile, DSL or imported, whichever TU includes import.h first. The adapter's imp_tiles.hip
    # carries the same #ifndef-guarded define from the same imports.json max, so the two agree and the include order
    # of dsl_tiles vs imp_tiles no longer matters (it did until a model folded layer 0, making dsl_tiles first).
    lds = max([i.get("lds_bytes", 0) for i in imp.values()] + [16])
    guard = f"#ifndef ETX_IMPORT_LDS\n#define ETX_IMPORT_LDS {lds}\n#endif"
    source = "\n".join(src).replace("@ETX_IMPORT_LDS@", guard) + "\n"
    if "source_prelude" in prims.machine_or_default(a.machine).primitives:
        # GEMV was emitted using the legacy spelling; replace its marked lowerings too.
        source = source.replace(prims.lower("gfx942", "uniform"), prims.lower(a.machine, "uniform"))
        source = source.replace(prims.lower("gfx942", "wave_sum0"), prims.lower(a.machine, "wave_sum0"))
    Path(a.tiles).write_text(prims.emit_source(source, a.machine, lds_bytes=lds))
    print(f"dsl ops {a.ops}: {a.tiles}; {a.imports_json} updated")


if __name__ == "__main__":
    main()
