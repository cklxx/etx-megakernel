"""Full-model pack path and checking-host snapshot finalizer, without downloads.

Reuse prep.py for weights, the supplied independent HF golden, and host --check
for live ORIGINAL argument blocks and independent original DSL output snapshots.
Preparation is outside the 900-second measurement window. CPU --dry-run never
executes a host or reads weight data. No historical certificate is issued.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for chunk in iter(lambda: f.read(8*1024*1024), b''):
            h.update(chunk)
    return h.hexdigest()


def sha_slice(path,offset,size):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        f.seek(offset)
        while size:
            b=f.read(min(size,8*1024*1024))
            if not b: raise ValueError('truncated packed weight slice')
            h.update(b); size-=len(b)
    return h.hexdigest()


def finalize(directory, host, plan, checks):
    directory, host, plan = map(Path, (directory, host, plan))
    log = Path(checks).read_text()
    if 'CHECK OK: 0 launch(es) differ' not in log or 'CHECK-IMPORTED' not in log:
        raise ValueError('capture requires completed original host import check')
    for role in ('moe_up', 'moe_down'):
        base = directory/role
        lines = (base/'capture.txt').read_text().splitlines()
        layer, position, first, count, total, offset, size = map(int, lines[0].split())
        weight_path, wo, wn = shlex.split(lines[1])
        weight_path = str(Path(weight_path).resolve())
        buffers = [dict(file=weight_path, offset=int(wo), bytes=int(wn),slice_sha256=sha_slice(weight_path,int(wo),int(wn)))]
        for file in ('input.bin', 'output.bin', 'ids.bin', 'weights.bin'):
            p = base/file
            buffers.append(dict(file=str(p.resolve()), offset=0, bytes=p.stat().st_size, sha256=sha(p)))
        args = base/'arguments.bin'
        reference = base/'reference.bin'
        if args.stat().st_size != 160 or reference.stat().st_size != size:
            raise ValueError('invalid original capture size')
        manifest = dict(version=1, precision='bf16', batch=1, context=1024, role=role,
            layer=layer, position=position, first=first, count=count, total_tasks=total,
            arguments=str(args.resolve()), arguments_sha256=sha(args), buffers=buffers,
            reference=dict(file=str(reference.resolve()), sha256=sha(reference), output_offset=offset, bytes=size,
                provenance='independent unchanged DSL constituent in original full-model host --check',
                original_host_sha256=sha(host), plan_sha256=sha(plan), check_log_sha256=sha(checks)),
            full_model_tokens='REQUIRES_SEPARATE_32/32', gpu_import_check_log=str(Path(checks).resolve()))
        (base/'pack.json').write_text(json.dumps(manifest, indent=2)+'\n')
    return directory


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--src', type=Path, help='local HF checkpoint to pack with existing prep.py')
    p.add_argument('--model', type=Path, required=True)
    p.add_argument('--golden', type=Path, required=True, help='independent HF golden, never generated by candidate')
    p.add_argument('--host', type=Path, required=True, help='original CHECK+CAPTURE host')
    p.add_argument('--plan', type=Path, required=True)
    p.add_argument('--layer', type=int, required=True)
    p.add_argument('--task', type=int, required=True)
    p.add_argument('--position', type=int, default=1040)
    p.add_argument('--deadline', type=float, required=True, help='seconds, enforced over entire preparation')
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--dry-run', action='store_true')
    a = p.parse_args()
    if not 0 <= a.layer < 48 or a.task < 0 or a.deadline <= 0:
        p.error('invalid capture selectors/deadline')
    commands = []
    if a.src:
        commands.append([sys.executable, 'examples/vllm_llm/prep.py', '--src', str(a.src), '--out', str(a.model), '--maxlen', '1072'])
    commands.append([str(a.host.resolve()), str(a.model.resolve()), str(a.plan.resolve()),
        '--golden', str(a.golden.resolve()), '--gen', '32', '--check', '48', '--check-pos', str(a.position)])
    if a.dry_run:
        print(json.dumps(dict(commands=commands, full_model_pack='existing prep.py vl.bin/vl.manifest', cpu_only=True)))
        return
    import time
    deadline = time.monotonic()+a.deadline
    a.output.mkdir(parents=True, exist_ok=False)
    for role in ('moe_up', 'moe_down'):
        (a.output/role).mkdir()
    env = dict(os.environ, ETX_BF16_CAPTURE_DIR=str(a.output.resolve()),
        ETX_BF16_CAPTURE_LAYER=str(a.layer), ETX_BF16_CAPTURE_TASK=str(a.task))
    for index, cmd in enumerate(commands):
        print('PREP '+shlex.join(cmd), flush=True)
        with (a.output/f'prepare_{index}.log').open('w') as f:
            subprocess.run(cmd, env=env, stdout=f, stderr=subprocess.STDOUT,
                           timeout=max(.01, deadline-time.monotonic()), check=True)
    finalize(a.output, a.host, a.plan, a.output/f'prepare_{len(commands)-1}.log')


if __name__ == '__main__':
    main()
