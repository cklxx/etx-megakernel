"""The pre-GPU record of the ds_inplace session, generated from the committed records only (no narration).

  python -m examples.dsv2lite.pregpu_report      # writes examples/dsv2lite/results/PRE-GPU.md
Reads: results/levers/*.json (verify_lever), results/stages/stage_table.json (stage_table), the session job file.
"""
from __future__ import annotations

import json
from pathlib import Path

from etx.experiments.jobs import load_session
from examples.dsv2lite import arms
from examples.dsv2lite.pinned import FLEET_COMMIT, FLEET_SRC_SHA256

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "examples/dsv2lite/results"


def main() -> int:
    recs = {p.stem: json.loads(p.read_text()) for p in sorted((RES / "levers").glob("*.json"))}
    default = recs["default"]["default"]
    st = json.loads((RES / "stages/stage_table.json").read_text())
    jobs, limit = load_session(ROOT / "examples/sessions/ds_inplace.py")
    gpu = [j.name for j in jobs if j.lane == "gpu"]
    md = ["# ds_inplace: pre-GPU record", "",
          "Generated by `python -m examples.dsv2lite.pregpu_report` from the committed records (do not edit).", "",
          "## Pinned inputs", "",
          f"- fleet source: commit {FLEET_COMMIT}, content hash `{FLEET_SRC_SHA256[:16]}` (examples/dsv2lite/pinned.py)",
          f"- default megakernel (ROCm 7.2.4, gfx942): isa `{default['isa_sha256'][:16]}`, "
          f"{default['resources']['vgpr']} VGPR / {default['resources']['agpr']} AGPR / "
          f"{default['resources']['scratch']} B scratch / {default['resources']['lds']} B LDS / "
          f"{default['resources']['occupancy']} wave/SIMD", "",
          "## Every arm, local gates (results/levers/*.json)", "",
          "| arm | verdict | CPU gates | VGPR | AGPR | scratch B/lane | LDS B | waves/SIMD | NT weight loads | vmcnt(0) waits |",
          "|---|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for name, r in recs.items():
        b = r.get("arm_build", r["default"])
        res, s = b["resources"], b["static"]
        md.append(f"| {name} | {r.get('verdict', 'PASS')} | {r['cpu_gates']['summary']} | {res['vgpr']} | {res['agpr']} | "
                  f"{res['scratch']} | {res['lds']} | {res['occupancy']} | {s['nt_weight_loads']} | {s['vmcnt0_waits']} |")
    a, sim = st["summary"]["arithmetic"], st["summary"]["simulated"]
    md += ["", "## Expected, per stage (results/stages/stage_table.md)", "",
           "| stage | current us | expected us | delta us | lever | local verification |", "|---|---:|---:|---:|---|---|"]
    for r in st["rows"]:
        md.append(f"| {r['stage']} | {r['current_us']:.2f} | {r['expected_us']:.2f} | {r['delta_us']:.2f} | {r['lever']} | "
                  f"{r.get('status', '')} |")
    md += ["", f"- device step {st['summary']['untraced_device_us']} us -> arithmetic {a['step_us']:.1f} us "
               f"({a['tok_s']:.1f} tok/s), simulated plan {sim['step_us']:.1f} us ({sim['tok_s']:.1f} tok/s)",
           f"- byte limit {st['summary']['limit']['step_us']:.1f} us ({st['summary']['limit']['tok_s']:.0f} tok/s)", "",
           "## The session (examples/sessions/ds_inplace.py)", "",
           f"- {len(jobs)} jobs, hard stop {limit} s; GPU jobs in order: {', '.join(gpu)}",
           f"- arms: " + "; ".join(f"{k} = {'+'.join(a.levers) or 'default'}" for k, a in arms.ARMS.items()),
           f"- decision (combined arm vs default, device): {arms.ARMS['all'].rule.text}; "
           "32/32 tokens + 27/27 layers + 32/32 warm-up in every invocation",
           f"- invocations: baseline 10, all 15, traces 2, single levers {10 * len(arms.SINGLE)} = "
           f"{10 + 15 + 2 + 10 * len(arms.SINGLE)}"]
    out = RES / "PRE-GPU.md"
    out.write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
