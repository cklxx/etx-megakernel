#!/usr/bin/env python3
"""Re-run the existing census on freshly emitted source, without changing kept build.

python -m docs... is not needed: invoke with the repository's .venv Python.
Modes: baseline (git source at 9af85ae), c1, c5 (norm hoist), combined.
Retains optimized device IR/ISA locally, commits counts and resources only.
"""
import argparse
import contextlib
import importlib.util
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import types

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from etx.ops import attnprep, gemv, topk
from etx.ops.emit import HEADER


def run(mode, out):
    os.environ['ETX_VL_ROUTER_NARROW'] = '1' if mode in ('c1', 'combined') else '0'
    # Load the emitter in isolation; never modify the shared kept-build symlink.
    g = types.ModuleType('candidate_gemv'); g.__file__ = str(ROOT / 'etx/ops/gemv.py')
    code = subprocess.check_output(['git', 'show', '9af85ae:etx/ops/gemv.py'], text=True) if mode == 'baseline' else (ROOT / 'etx/ops/gemv.py').read_text()
    exec(compile(code, g.__file__, 'exec'), g.__dict__)
    work = out / mode; work.mkdir(parents=True, exist_ok=True)
    src = list(HEADER)
    for op in (attnprep, g, topk):
        src.append('\n'.join(ln for ln in op.emit_tiles().splitlines() if not ln.startswith(('#pragma once', '#include', '// generated by'))))
    (work/'dsl_tiles.hip').write_text('\n'.join(src).replace('@ETX_IMPORT_LDS@', '#ifndef ETX_IMPORT_LDS\n#define ETX_IMPORT_LDS 21120\n#endif')+'\n')
    (work/'etx_lowering.h').write_bytes((ROOT/'build/qwen300-rocm-on/etx_lowering.h').read_bytes())
    spec = importlib.util.spec_from_file_location('original_census', ROOT/'docs/master-table-2026-10-11/isa.py')
    census = importlib.util.module_from_spec(spec); spec.loader.exec_module(census)
    census.B = work; census.SRC = work/'dsl_tiles.hip'
    if mode in ('c5', 'combined'):
        census.FLAGS.append('-DETX_DSL_NORM_HOIST')
    if mode in ('c1', 'combined'):
        census.TILES.append(('k_router_fold', 'etx_tile_dsl_gemv_router_fold'))
        census.WRAP += 'K(k_router_fold, etx_tile_dsl_gemv_router_fold)\n'
    original = census.compile_s
    census.compile_s = lambda unused: original(work)
    with (out/f'{mode}.txt').open('w') as f, contextlib.redirect_stdout(f):
        census.main()
    print(f'CENSUS {mode}: {out / (mode + ".txt")}', flush=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('mode', choices=('baseline', 'c1', 'c5', 'combined'))
    ap.add_argument('--out', type=Path, default=Path('/tmp/etx-isafixes-isa'))
    a = ap.parse_args(); a.out = a.out.resolve(); a.out.mkdir(parents=True, exist_ok=True)
    run(a.mode, a.out)
